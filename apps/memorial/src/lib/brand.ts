export function brandCssVariables(brand: BrandProfile): Record<string, string> {
  return {
    '--brand-primary': brand.primaryColor,
    '--brand-secondary': brand.secondaryColor,
    '--brand-accent': brand.accentColor,
    '--brand-background': brand.backgroundColor,
    '--brand-text': brand.textColor,
    '--brand-radius': brand.borderRadius,
    '--brand-font': brand.fontFamily === 'serif' ? 'Georgia, serif' : brand.fontFamily === 'elegant' ? 'Cormorant Garamond, Georgia, serif' : brand.fontFamily === 'large-print' ? 'Atkinson Hyperlegible, Verdana, sans-serif' : 'Source Sans 3, system-ui, sans-serif',
  };
}

